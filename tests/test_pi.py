"""
Project Infinity lists and an author's mod-forge.json (M2, GUI-AUDIT item 13).

A PI list names components by LABEL. The staged tp2 decides what a LABEL is;
krion64's records stand in for a mod not yet staged and agree with the tp2s
for 708 of 732 LABELs (docs/TESTING.md) - the 24 others are why the tp2 wins.
"""
import json
import os

import pytest

from iemod_fetch import api
from iemod_fetch.errors import ConfigError
from iemod_fetch.pi import (TP2, LabelIndex, Target, add_krion,
                            index_from_described, parse_pi_list, selection_from_pi)
from iemod_fetch.rules import RuleSet, mod_forge_record

HERE = os.path.dirname(__file__)

LIST = """\
// Install order for EET - Generated by Infinity Mod Forge

//Patches
A7-DLCMERGER-MERGE_SOD;DLC Merger - Merge "Siege of Dragonspear" DLC
eefixpack:0;EE Fixpack - Core Fixes
"""

DLC_TP2 = """BACKUP ~DlcMerger/backup~
LANGUAGE ~English~ ~english~ ~DlcMerger/tra/english/setup.tra~
BEGIN ~Merge SoD~ DESIGNATED 1
LABEL ~A7-DLCMERGER-MERGE_SOD~
"""

KRION_DLC = {"t": "DlcMerger", "co": [
    {"n": "Merge SoD", "cn": 1, "wp": "DlcMerger\\DlcMerger.tp2", "wc": 1,
     "pi": "A7-DLCMERGER-MERGE_SOD"}]}
KRION_FIXPACK = {"t": "eefixpack", "co": [
    {"n": "Core Fixes", "cn": 0, "wp": "eefixpack\\setup-eefixpack.tp2", "wc": 0}]}


def stage(root, folder, name, text):
    os.makedirs(os.path.join(root, folder), exist_ok=True)
    with open(os.path.join(root, folder, name), "w", encoding="utf-8") as fh:
        fh.write(text)


# ------------------------------------------------------------ the format
def test_lines_comments_and_order():
    lines = parse_pi_list(LIST)
    assert [(line.ident, line.line) for line in lines] == [
        ("A7-DLCMERGER-MERGE_SOD", 4), ("eefixpack:0", 5)]
    assert lines[0].description == 'DLC Merger - Merge "Siege of Dragonspear" DLC'


def test_a_line_without_a_semicolon_is_refused_with_its_number():
    with pytest.raises(ConfigError, match="line 2"):
        parse_pi_list("a;b\nnot a pi line\n")


# --------------------------------------------------------------- resolving
def test_labels_from_krion_resolve_a_list_with_a_note_each():
    index = add_krion(LabelIndex(), [KRION_DLC, KRION_FIXPACK])
    selection, notes = selection_from_pi(parse_pi_list(LIST), "BGEE", index)
    (install,) = selection.installs
    assert install.game == "BGEE"
    assert [(c.tp2, c.component) for c in install.components] == [
        ("DlcMerger/DlcMerger.tp2", 1), ("eefixpack/setup-eefixpack.tp2", 0)]
    assert len(notes) == 2 and all("krion64" in note for note in notes)


def test_the_staged_tp2_wins_over_krion64():
    """cd_tweaks_drab_commoners: krion64 says iwdification #20, the tp2 says
    cdtweaks #100 (measured, 2026-10)."""
    index = add_krion(LabelIndex(), [{"t": "iwdification", "co": [
        {"cn": 20, "wc": 20, "wp": "iwdification/setup-iwdification.tp2",
         "pi": "cd_tweaks_drab_commoners"}]}])
    index.add("CD_TWEAKS_DRAB_COMMONERS", Target("cdtweaks/setup-cdtweaks.tp2", 100, TP2))
    # and a later krion64 record cannot take it back
    add_krion(index, [{"t": "x", "co": [{"wc": 1, "wp": "x/x.tp2",
                                         "pi": "cd_tweaks_drab_commoners"}]}])
    selection, notes = selection_from_pi(
        parse_pi_list("cd_tweaks_drab_commoners;Tweaks - drab commoners"), "EET", index)
    assert selection.installs[0].components[0].tp2 == "cdtweaks/setup-cdtweaks.tp2"
    assert notes == []


def test_unknown_entries_are_all_listed_never_guessed_from_the_description():
    with pytest.raises(ConfigError) as caught:
        selection_from_pi(parse_pi_list(LIST), "EET", LabelIndex())
    assert "A7-DLCMERGER-MERGE_SOD" in str(caught.value)
    assert "no tp2 known for folder 'eefixpack'" in str(caught.value)


def test_an_unsafe_tp2_path_from_krion64_is_refused():
    index = add_krion(LabelIndex(), [{"t": "x", "co": [
        {"wc": 1, "wp": "x/../../evil.tp2", "pi": "EVIL"}]}])
    with pytest.raises(ConfigError, match="unsafe"):
        selection_from_pi(parse_pi_list("EVIL;x"), "EET", index)


def test_a_label_two_tp2s_claim_is_refused():
    index = LabelIndex()
    index.add("SAME", Target("a/a.tp2", 1, TP2))
    index.add("SAME", Target("b/b.tp2", 2, TP2))
    with pytest.raises(ConfigError, match="more than one component"):
        selection_from_pi(parse_pi_list("SAME;x"), "EET", index)


def test_staged_tp2_labels_through_describe(tmp_path):
    stage(str(tmp_path), "DlcMerger", "DlcMerger.tp2", DLC_TP2)
    index = index_from_described(api.describe_mods(str(tmp_path)))
    assert index.labels["a7-dlcmerger-merge_sod"] == Target("DlcMerger/DlcMerger.tp2", 1, TP2)


# ------------------------------------------------------------- end to end
def test_pi_list_is_what_is_wanted_in_a_run(tmp_path):
    mods = tmp_path / "Mods"
    stage(str(mods), "DlcMerger", "DlcMerger.tp2", DLC_TP2)
    stage(str(mods), "eefixpack", "setup-eefixpack.tp2", "BEGIN ~Core Fixes~\n")
    pi_list = tmp_path / "install-EET.txt"
    pi_list.write_text(LIST)
    out = tmp_path / "selection.json"
    api.run(api.Settings(pi_list=f"{pi_list}:BGEE", target=str(mods), emit_selection=str(out),
                         check_only=True, quiet=True, no_update_data=True,
                         no_default_data=True,
                         manifest=os.path.join(HERE, "data", "mod_downloads.json")))
    components = json.loads(out.read_text())["installs"][0]["components"]
    assert [(c["tp2"], c["component"]) for c in components] == [
        ("DlcMerger/DlcMerger.tp2", 1), ("eefixpack/setup-eefixpack.tp2", 0)]


def test_pi_list_needs_its_game(tmp_path):
    with pytest.raises(ConfigError, match="needs the game"):
        api.run(api.Settings(pi_list=str(tmp_path / "x.txt"), check_only=True,
                             no_update_data=True))


# ------------------------------------------------------------ mod-forge.json
FORGE = {
    "tp2": "MyMod", "name": "My Cool Mod", "author": "me", "components": [
        {"name": "Main component", "number": 0, "label": "mymod_main"}],
    "conflicts": [{"mod": "OtherMod", "severity": "partial",
                   "reason": "Both edit BALDUR.BCS.", "myComponents": "#0",
                   "theirComponents": "#100 #200"}],
    "dependencies": [{"mod": "EET", "type": "hard", "reason": "Needs the EET journal."}],
    "knownIssues": [{"severity": "warning", "description": "Portrait missing on first try.",
                     "workaround": "Re-run.", "components": [0]}],
}


def test_mod_forge_json_becomes_rules_and_notes(tmp_path):
    path = tmp_path / "mod-forge.json"
    path.write_text(json.dumps(FORGE))
    ruleset = RuleSet.load_file(str(path))
    kinds = sorted((r.kind, r.left.mod, r.right[0].mod) for r in ruleset.rules)
    assert kinds == [("depends", "mymod", "eet"), ("incompatible", "mymod", "othermod")]
    conflict = next(r for r in ruleset.rules if r.kind == "incompatible")
    assert conflict.severity == "warning" and conflict.right[0].components == {100, 200}
    assert conflict.source == "the mod's own mod-forge.json"
    assert ruleset.notes[0].summary == "Portrait missing on first try."


def test_a_json_that_is_not_a_mod_forge_file_is_not_read_as_one():
    assert mod_forge_record({"tp2": "x"}) is None            # no components
    assert mod_forge_record(["not", "a", "dict"]) is None


def test_a_staged_mods_mod_forge_json_reaches_the_check(tmp_path):
    mods = tmp_path / "Mods"
    stage(str(mods), "MyMod", "setup-mymod.tp2", "BEGIN ~Main~\n")
    stage(str(mods), "OtherMod", "setup-othermod.tp2", "BEGIN ~A~ DESIGNATED 100\n")
    stage(str(mods), "MyMod", "mod-forge.json", json.dumps(FORGE))
    log = tmp_path / "WeiDU.log"
    log.write_text("~MyMod/setup-mymod.tp2~ #0 #0 // Main\n"
                   "~OtherMod/setup-othermod.tp2~ #0 #100 // A\n")
    report = tmp_path / "conflicts.json"
    (tmp_path / "rules").mkdir()               # no community rules: the author's alone
    api.run(api.Settings(weidu_log=[f"{log}:BG2EE"], target=str(mods), check_only=True,
                         quiet=True, conflict_report=str(report), rules=[str(tmp_path / "rules")],
                         no_update_data=True, no_default_data=True,
                         manifest=os.path.join(HERE, "data", "mod_downloads.json")))
    findings = json.loads(report.read_text())["findings"]
    assert any(f["kind"] == "incompatible" and f["right"]["mod"] == "OtherMod"
               for f in findings), findings


